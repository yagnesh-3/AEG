/**
 * Compact seed shape. Milestone dates are derived from `startedOn` +
 * `targetCompletion` so the M1-M7 tracker always reads consistently.
 */
interface Seed {
  name: string;
  category: ProjectCategory;
  status: ProjectStatus;
  location: string;
  state: string;
  country: string;
  summary: string;
  description: string;
  lots?: number;
  areaHectares: number;
  startedOn: string;
  targetCompletion: string;
  lifecycleStage: LifecycleStage;
  projectManager: string;
  /** M1-M7 statuses, in order. */
  ms: MilestoneStatus[];
  landCost: number;
  developmentBudget: number;
  spendPct: number;
  projectedRevenue: number;
  realisedPct: number;
  capitalTarget: number;
  raisedPct: number;
  targetIrrPct: number;
  tone: [string, string];
  featured?: boolean;
}

const D = (s: string) => new Date(`${s}T00:00:00Z`);

/** Shift a YYYY-MM-DD date forward by a number of months. */
function shiftMonths(iso: string, months: number): string {
  const d = D(iso);
  d.setUTCMonth(d.getUTCMonth() + months);
  return d.toISOString().slice(0, 10);
}

const TIMELINE_SHIFT_MONTHS = 9;
const TODAY_ISO = new Date().toISOString().slice(0, 10);

/** Spread the seven milestones evenly across the project window. */
function buildMilestones(seed: Seed, startedOn: string, targetCompletion: string): Milestone[] {
  const start = D(startedOn).getTime();
  const end = D(targetCompletion).getTime();
  const span = end - start;

  return MILESTONES.map((m, i) => {
    const status = seed.ms[i] ?? 'not-started';
    const target = new Date(start + (span * (i + 1)) / (MILESTONES.length + 0.35));
    const targetDate = target.toISOString().slice(0, 10);

    // Completed milestones land within a few weeks either side of target.
    const drift = ((i * 37) % 45) - 18;
    let actual: string | null = null;
    if (status === 'complete') {
      const raw = new Date(target.getTime() + drift * 86_400_000).toISOString().slice(0, 10);
      // A completed milestone is never dated in the future.
      actual = raw > TODAY_ISO ? TODAY_ISO : raw;
    }

    return { code: m.code, status, targetDate, actualDate: actual };
  });
}

