function buildProject(seed: Seed, index: number): Project {
  const realisedRevenue = Math.round(seed.projectedRevenue * (seed.realisedPct / 100));
  const startedOn = shiftMonths(seed.startedOn, TIMELINE_SHIFT_MONTHS);
  const targetCompletion = shiftMonths(seed.targetCompletion, TIMELINE_SHIFT_MONTHS);
  return {
    id: `p-${String(index + 1).padStart(2, '0')}`,
    slug: slugify(seed.name),
    name: seed.name,
    category: seed.category,
    status: seed.status,
    location: seed.location,
    state: seed.state,
    country: seed.country,
    summary: seed.summary,
    description: seed.description,
    lots: seed.lots,
    areaHectares: seed.areaHectares,
    startedOn,
    targetCompletion,
    lifecycleStage: seed.lifecycleStage,
    projectManager: seed.projectManager,
    milestones: buildMilestones(seed, startedOn, targetCompletion),
    financials: {
      landCost: seed.landCost,
      developmentBudget: seed.developmentBudget,
      developmentSpendToDate: Math.round(seed.developmentBudget * (seed.spendPct / 100)),
      projectedRevenue: seed.projectedRevenue,
      realisedRevenue,
      investorCapitalRaised: Math.round(seed.capitalTarget * (seed.raisedPct / 100)),
      investorCapitalTarget: seed.capitalTarget,
      targetIrrPct: seed.targetIrrPct,
    },
    imageTone: seed.tone,
    featured: seed.featured ?? false,
  };
}

